function glyphSvg(rows, fg = FG, bg = BG) {
  let d = '';
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') { x++; continue; }
      let e = x; while (e < row.length && row[e] === '#') e++;
      d += `M${x} ${y + 1}h${e - x}v1h-${e - x}z`;      // 1 pixel of headroom above the glyph
      x = e;
    }
  });
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${CELL_W}" height="${CELL_H}" viewBox="0 0 ${CELL_W} ${CELL_H}" shape-rendering="crispEdges">` +
    `<rect width="${CELL_W}" height="${CELL_H}" fill="${bg}"/>${d ? `<path fill="${fg}" d="${d}"/>` : ''}</svg>`;
}

// costumes in ascii order: costume number = code - 31. named after the character itself, which lets the
// project turn typed text back into character codes ("switch costume to (letter)" is case sensitive).
function costumes(svgCostume) {
  const out = [];
  for (let c = 32; c < 127; c++) {
    const ch = String.fromCharCode(c);
    const g = GLYPHS[ch];
    if (!g) throw new Error('no glyph for ' + JSON.stringify(ch));
    const rows = g.split(' ');
    if (rows.length !== 7 || rows.some((r) => r.length !== 5)) throw new Error('bad glyph ' + JSON.stringify(ch));
    out.push(svgCostume(ch, glyphSvg(rows), 0, 0));
  }
  // four arrows for the key legend (costumes 97..100: left up right down)
  const ARROWS = {
    left: '..... ..#.. .#... ##### .#... ..#.. .....',
    up: '..#.. .###. #.#.# ..#.. ..#.. ..#.. .....',
    right: '..... ..#.. ...#. ##### ...#. ..#.. .....',
    down: '..... ..#.. ..#.. ..#.. #.#.# .###. ..#..',
  };
  const extra = [];
  for (const [name, g] of Object.entries(ARROWS)) extra.push(svgCostume(name, glyphSvg(g.split(' '), '#ffd866'), 0, 0));
  // cursor: a block in the bottom of the cell
  out.push(svgCostume('cursor', `<svg xmlns="http://www.w3.org/2000/svg" width="${CELL_W}" height="${CELL_H}" viewBox="0 0 ${CELL_W} ${CELL_H}" shape-rendering="crispEdges"><rect width="${CELL_W}" height="${CELL_H}" fill="${BG}" fill-opacity="0.01"/><rect x="0" y="1" width="5" height="7" fill="${FG}" fill-opacity="0.75"/></svg>`, 0, 0));
  out.push(...extra);
  return out;
}

